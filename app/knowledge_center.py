def _control(
    name: str,
    control_type: str,
    description: str,
    when_to_use: str,
    caution: str,
    platform: str = "both",
) -> dict[str, str]:
    return {
        "name": name,
        "type": control_type,
        "description": description,
        "whenToUse": when_to_use,
        "caution": caution,
        "platform": platform,
    }


def _command(label: str, command: str, notes: str = "") -> dict[str, str]:
    return {"label": label, "command": command, "notes": notes}


def _scenario(title: str, description: str) -> dict[str, str]:
    return {"title": title, "description": description}


def _faq(issue: str, guidance: str) -> dict[str, str]:
    return {"issue": issue, "guidance": guidance}


def _flatten_text(value: Any) -> list[str]:
    chunks: list[str] = []
    if isinstance(value, dict):
        for nested in value.values():
            chunks.extend(_flatten_text(nested))
    elif isinstance(value, list):
        for item in value:
            chunks.extend(_flatten_text(item))
    elif value is None:
        return chunks
    else:
        chunks.append(str(value))
    return chunks


def _prepare_article(article: dict[str, Any]) -> dict[str, Any]:
    prepared = deepcopy(article)
    has_nethunter = bool(prepared.get("nethunter"))
    has_kali = bool(prepared.get("kaliLinux"))
    if has_nethunter and has_kali:
        prepared["platform"] = "both"
        prepared["contexts"] = ["nethunter", "kali"]
    elif has_nethunter:
        prepared["platform"] = "nethunter"
        prepared["contexts"] = ["nethunter"]
    else:
        prepared["platform"] = "kali"
        prepared["contexts"] = ["kali"]
    prepared["searchText"] = " ".join(_flatten_text(prepared)).lower()
    return prepared


